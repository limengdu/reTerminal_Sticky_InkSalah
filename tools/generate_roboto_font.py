#!/usr/bin/env python3
"""Bake the vendored Roboto font into monochrome firmware glyphs."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SIZES = (20, 22, 24, 26, 28, 32, 36, 40, 48)
CODEPOINTS = tuple(range(32, 127)) + tuple(range(160, 384)) + (0x2013, 0x2014, 0x2019)


def main():
    records, faces, data = [], [], bytearray()
    for size in SIZES:
        for weight in (400, 700):
            font = ImageFont.truetype(str(ROOT / "assets/fonts/Roboto.ttf"), size)
            font.set_variation_by_axes([weight, 100])
            first = len(records)
            for codepoint in CODEPOINTS:
                char = chr(codepoint)
                left, top, right, bottom = font.getbbox(char, anchor="ls")
                width, height = right - left, bottom - top
                image = Image.new("L", (max(1, width), max(1, height)), 0)
                ImageDraw.Draw(image).text((-left, -top), char, font=font, anchor="ls", fill=255)
                stride = (width + 7) // 8
                pixels = bytearray(stride * height)
                for y in range(height):
                    for x in range(width):
                        if image.getpixel((x, y)) >= 112:
                            pixels[y * stride + x // 8] |= 1 << (7 - x % 8)
                records.append((codepoint, len(data), width, height, left,
                                top + round(size * 0.8), round(font.getlength(char))))
                data.extend(pixels)
            faces.append((size, weight == 700, first, len(CODEPOINTS)))
    lines = ["// Generated by tools/generate_roboto_font.py from Roboto (OFL-1.1).",
             "constexpr uint8_t kRobotoPixels[] = {"]
    for offset in range(0, len(data), 24):
        lines.append("    " + ",".join(str(v) for v in data[offset:offset + 24]) + ",")
    lines.extend(["};", "constexpr FontGlyph kRobotoGlyphs[] = {"])
    lines.extend("    {" + ",".join(str(v) for v in record) + "}," for record in records)
    lines.extend(["};", "constexpr FontFace kRobotoFaces[] = {"])
    for size, bold, first, count in faces:
        lines.append(f"    {{{size}, {'true' if bold else 'false'}, kRobotoGlyphs + {first}, {count}}},")
    lines.append("};\n")
    (ROOT / "src/ui/roboto_font_data.inc").write_text("\n".join(lines))
    print(f"Roboto: {len(faces)} faces, {len(records)} glyphs, {len(data)} bitmap bytes")


if __name__ == "__main__":
    main()
