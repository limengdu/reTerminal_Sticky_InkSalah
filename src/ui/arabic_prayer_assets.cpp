        return {37U, 25U, 5U, kFajr};
    case PrayerTimeSlot::Sunrise:
        return {53U, 24U, 7U, kSunrise};
    case PrayerTimeSlot::Dhuhr:
        return {39U, 26U, 5U, kDhuhr};
    case PrayerTimeSlot::Asr:
        return {47U, 18U, 6U, kAsr};
    case PrayerTimeSlot::Maghrib:
        return {47U, 23U, 6U, kMaghrib};
    case PrayerTimeSlot::Isha:
        return {46U, 20U, 6U, kIsha};
    case PrayerTimeSlot::Qiyam:
